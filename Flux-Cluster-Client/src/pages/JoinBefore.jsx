import React, { useState } from 'react';
import { useNavigate } from "react-router-dom";
import { useSEO } from '../hooks/useSEO';

const JoinBefore = () => {
    useSEO({
        title: 'Join Distributed Swarm Node',
        description: 'Contribute your browser idle GPU power to the FluxCluster distributed compute swarm. Connect via WebRTC data channels to crunch path-traced tiles with zero local installation.',
        canonical: '/join'
    });

    const navigate = useNavigate();
    const [RoomID, setRoomID] = useState("");
    const [error, setError] = useState("");

    const joinRoom = (e) => {
        if (e) e.preventDefault();
        const cleanId = RoomID.trim();
        if (!cleanId) {
            setError("Room ID is required to initiate connection.");
            return;
        }
        setError("");
        navigate(`/joined?roomId=${encodeURIComponent(cleanId)}`);
    };

    const handlePaste = async () => {
        try {
            const text = await navigator.clipboard.readText();
            if (text) {
                setRoomID(text.trim());
                setError("");
            }
        } catch (err) {
            console.warn("Clipboard access denied or unavailable:", err);
        }
    };

    return (
        <div className="font-sans antialiased text-[#ededed] bg-[#141415] w-full max-w-lg max-h-[min(92vh,680px)] flex flex-col overflow-hidden border border-white/[0.08] rounded-xl shadow-2xl my-auto select-none">
            {/* Header */}
            <header className="flex items-center justify-between px-5 py-3.5 border-b border-white/[0.08] bg-[#19191b]/50 shrink-0">
                <div className="flex items-center gap-3">
                    <span className="text-xs font-mono font-medium text-[#AF3240] px-2 py-0.5 rounded bg-[#AF3240]/10 border border-[#AF3240]/20">
                        FluxCluster
                    </span>
                    <h1 className="text-xs font-mono font-medium text-[#ededed] m-0 p-0">
                        Swarm Node Peering
                    </h1>
                </div>

                <div className="flex items-center gap-2">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#4cc38a]" />
                    <span className="text-xs font-mono text-[#85858b]">
                        Cluster ready
                    </span>
                </div>
            </header>

            {/* Section 01: Peering & Session Credentials */}
            <div className="p-5 sm:p-6 border-b border-white/[0.06]">
                <div className="flex items-center justify-between mb-3 text-xs font-mono">
                    <span className="text-[#85858b] uppercase tracking-wider text-[11px]">
                        01 · Session Credentials
                    </span>
                    <span className="text-[#85858b]">WebRTC SCTP</span>
                </div>

                <p className="text-xs sm:text-sm text-[#a1a1a6] leading-relaxed mb-5">
                    Connect local GPU and CPU compute to an active render cluster. Enter the session room code generated by the orchestrator.
                </p>

                <form onSubmit={joinRoom} className="flex flex-col gap-3">
                    <div className="flex flex-col gap-1.5">
                        <label htmlFor="session-room-id" className="text-xs font-mono text-[#85858b] flex justify-between">
                            <span>Session room code</span>
                            <span className="text-[#85858b]">Required</span>
                        </label>
                        <div className="relative flex items-center">
                            <input
                                id="session-room-id"
                                name="roomId"
                                aria-label="Session Room Code"
                                autoComplete="off"
                                placeholder="Paste or enter room code..."
                                className="w-full py-2.5 pl-3.5 pr-20 text-sm font-mono text-[#ededed] bg-[#19191b] border border-white/[0.08] rounded-lg outline-none focus:border-[#AF3240] focus:ring-1 focus:ring-[#AF3240]/40 transition-colors placeholder:text-[#85858b] placeholder:font-sans"
                                value={RoomID}
                                onChange={(e) => {
                                    setRoomID(e.target.value);
                                    if (error) setError("");
                                }}
                                autoFocus
                            />
                            <button
                                type="button"
                                onClick={handlePaste}
                                className="absolute right-1.5 text-xs font-mono px-2.5 py-1 rounded border border-white/[0.08] bg-[#232325] hover:bg-[#2c2c30] text-[#a1a1a6] hover:text-[#ededed] transition-colors cursor-pointer"
                                title="Paste from clipboard"
                            >
                                Paste
                            </button>
                        </div>
                        {error && (
                            <span className="text-xs font-mono text-[#e5484d] mt-1">
                                {error}
                            </span>
                        )}
                    </div>

                    <button
                        type="submit"
                        className="mt-2 text-xs font-mono font-medium w-full py-2.5 px-4 bg-[#AF3240] hover:bg-[#972935] text-white rounded-lg transition-colors cursor-pointer flex items-center justify-center gap-2 shadow-sm"
                    >
                        <span>Connect to swarm</span>
                        <svg className="w-3.5 h-3.5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="1.5">
                            <path strokeLinecap="round" strokeLinejoin="round" d="M13.5 4.5L21 12m0 0l-7.5 7.5M21 12H3" />
                        </svg>
                    </button>
                </form>
            </div>

            {/* Section 02: Client Telemetry & Hardware Probe */}
            <div className="p-5 sm:p-6 bg-[#141415]">
                <div className="flex items-center justify-between mb-3 text-xs font-mono">
                    <span className="text-[#85858b] uppercase tracking-wider text-[11px]">
                        02 · Client Diagnostics
                    </span>
                    <span className="text-[#85858b]">Telemetry</span>
                </div>

                <div className="grid grid-cols-2 gap-3 text-xs font-mono">
                    <div className="p-3 bg-[#19191b] border border-white/[0.06] rounded-lg">
                        <div className="text-[11px] text-[#85858b]">Runtime</div>
                        <div className="text-[#ededed] font-medium mt-0.5">WebGPU / WebGL2</div>
                    </div>
                    <div className="p-3 bg-[#19191b] border border-white/[0.06] rounded-lg">
                        <div className="text-[11px] text-[#85858b]">Daemon role</div>
                        <div className="text-[#ededed] font-medium mt-0.5">Worker node</div>
                    </div>
                    <div className="p-3 bg-[#19191b] border border-white/[0.06] rounded-lg">
                        <div className="text-[11px] text-[#85858b]">Peer protocol</div>
                        <div className="text-[#ededed] font-medium mt-0.5">Direct P2P channel</div>
                    </div>
                    <div className="p-3 bg-[#19191b] border border-white/[0.06] rounded-lg">
                        <div className="text-[11px] text-[#85858b]">Encryption</div>
                        <div className="text-[#4cc38a] font-medium mt-0.5">DTLS 1.3 secure</div>
                    </div>
                </div>
            </div>

            {/* Footer */}
            <footer className="px-5 py-2.5 border-t border-white/[0.08] bg-[#19191b]/50 flex items-center justify-between text-xs font-mono text-[#85858b]">
                <span>Status · Standby</span>
                <span>FluxCluster v2.4</span>
            </footer>
        </div>
    );
};

export default JoinBefore;
